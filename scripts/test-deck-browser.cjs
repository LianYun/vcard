const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_EXECUTABLE});
 const page = await browser.newPage({viewport:{width:1280,height:1000}});
 const errors=[]; page.on('pageerror', e=>errors.push(String(e)));
 await page.goto(process.env.DECK_TEST_URL || 'http://127.0.0.1:5188');
 await page.evaluate(()=>{localStorage.clear();localStorage.setItem('vibe-word:language:v1','zh-Hans');localStorage.setItem('vibe-word:decks:v1',JSON.stringify([{id:'default',name:'默认牌组'},{id:'english',name:'英语',exact:true},{id:'phrases',name:'日常短语',parentId:'english'}]));localStorage.setItem('vibe-word:cards:v1',JSON.stringify(Array.from({length:12},(_,n)=>({id:`deck-test:${n}`,front:`word ${n}`,back:`Meaning ${n}`,deckId:n<6?'phrases':'default',createdAt:Date.now()/1000}))));});
 await page.reload();
 await page.getByRole('navigation',{name:'牌组筛选'}).getByRole('button',{name:/^英语\s*6$/}).click();
 assert.equal(await page.locator('.library-row').count(),6);
 await page.getByRole('button',{name:'批量选择',exact:true}).click();
 await page.getByRole('button',{name:'全选',exact:true}).click();
 await page.getByRole('button',{name:'移动到…',exact:true}).click();
 await page.getByLabel('目标牌组').selectOption('default');
 await page.getByRole('button',{name:'确认移动',exact:true}).click();
 await page.getByRole('status').filter({hasText:'已将 6 张卡片移至 默认牌组'}).waitFor();
 assert.equal(await page.locator('.library-row').count(),0);
 await page.getByRole('button',{name:'管理牌组',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'新建牌组',exact:false}).click();
 await page.getByLabel('名称',{exact:true}).fill('阅读词汇');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('navigation',{name:'牌组筛选'}).getByRole('button',{name:'阅读词汇'}).waitFor();
 await page.getByRole('button',{name:'管理牌组',exact:true}).click();
 await page.getByRole('button',{name:'编辑 阅读词汇',exact:true}).click();
 await page.getByLabel('名称',{exact:true}).fill('阅读词汇更新');
 await page.getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('navigation',{name:'牌组筛选'}).getByRole('button',{name:'全部卡片'}).click();
 await page.locator('.library-browser').scrollIntoViewIfNeeded();
 await page.screenshot({path:'design/deck-library-desktop.png'});
 await page.getByRole('button',{name:'展开或折叠 英语',exact:true}).click();
 assert.equal(await page.getByRole('navigation',{name:'牌组筛选'}).getByRole('button',{name:'日常短语'}).count(),0);
 await page.getByRole('button',{name:'展开或折叠 英语',exact:true}).click();
 await page.getByRole('button',{name:'管理牌组',exact:true}).click();
 await page.getByRole('button',{name:'删除 阅读词汇更新',exact:true}).click();
 await page.getByRole('button',{name:'确认删除',exact:true}).click();
 await page.getByRole('status').filter({hasText:'牌组已删除'}).waitFor();
 await page.getByRole('button',{name:'管理牌组',exact:true}).click();
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('dialog[open]').count(),0);
 assert.equal(await page.getByRole('button',{name:'管理牌组',exact:true}).evaluate(e=>e===document.activeElement),true);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'全部牌组 ▾',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'默认牌组'}).click();
 assert.equal(await page.locator('.library-row').count(),12);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.locator('.library-browser').scrollIntoViewIfNeeded();await page.screenshot({path:'design/deck-library-mobile.png'});
 await page.getByRole('button',{name:'学习此牌组',exact:true}).click();
 await page.locator('.study-card').waitFor();
 assert.deepEqual(errors,[]);
 await browser.close();console.log('PASS deck UI: parent filter, bulk move, create/edit, dialog Escape/focus, mobile selector, 390px overflow, deck study');
})().catch(e=>{console.error(e);process.exit(1)});
