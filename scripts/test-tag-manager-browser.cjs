const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
    const errors = []
    page.on('pageerror', e => errors.push(String(e)))
    await page.goto(process.env.STUDY_TEST_URL || 'http://127.0.0.1:5189')
    await page.evaluate(() => {
      localStorage.clear()
      localStorage.setItem('vibe-word:language:v1', 'zh-Hans')
      localStorage.setItem('vibe-word:cards:v1', JSON.stringify([
        { id: 'a', front: 'Alpha', back: 'A', tags: ['old', 'shared'], createdAt: 1 },
        { id: 'b', front: 'Beta', back: 'B', tags: ['old'], createdAt: 1 },
        { id: 'c', front: 'Gamma', back: 'C', tags: [], createdAt: 1 },
      ]))
      localStorage.setItem('vibe-word:settings:v1', JSON.stringify({ newCardsPerDay: 20, studyScope: ['old'] }))
    })
    await page.reload()
    await page.getByRole('button', { name: '卡片库', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: '＋ 新建牌组', exact: true }).count(), 0)
    await page.getByRole('button', { name: '管理牌组', exact: true }).click()
    await page.getByRole('button', { name: '＋ 新建牌组', exact: true }).waitFor()
    await page.getByRole('button', { name: '‹ 返回卡片库', exact: true }).click()
    const before = await page.evaluate(() => localStorage.getItem('vibe-word:study:v2'))
    await page.getByRole('button', { name: '管理标签', exact: true }).click()
    await page.getByRole('button', { name: '＋ 创建标签', exact: true }).click()
    const create = page.getByRole('dialog', { name: '创建标签', exact: true })
    const submit = create.getByRole('button', { name: '创建标签', exact: true })
    assert.equal(await submit.isDisabled(), true)
    await create.getByRole('textbox', { name: '标签名称' }).fill('   ')
    assert.equal(await submit.isDisabled(), true)
    await create.getByRole('textbox').fill('old')
    await create.getByText('该标签已存在', { exact: true }).waitFor()
    assert.equal(await submit.isDisabled(), true)
    await create.getByRole('textbox').fill('  unused  ')
    await submit.click()
    await page.getByRole('button', { name: 'unused 包含 0 张卡片', exact: true }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: '卡片库', exact: true }).click()
    await page.getByRole('button', { name: '管理标签', exact: true }).click()
    await page.getByRole('button', { name: 'unused 包含 0 张卡片', exact: true }).waitFor()
    await page.getByRole('button', { name: '添加', exact: true }).click()
    await page.getByRole('combobox', { name: '选择标签', exact: true }).first().click()
    await page.getByRole('option', { name: 'unused', exact: true }).click()
    await page.getByRole('button', { name: '移除标签：unused', exact: true }).waitFor()
    await page.getByRole('button', { name: '卡片库', exact: true }).click()
    await page.getByRole('button', { name: '重命名标签：unused', exact: true }).click()
    const emptyEdit = page.getByRole('dialog', { name: '重命名标签', exact: true })
    await emptyEdit.getByRole('textbox').fill('empty-renamed')
    await emptyEdit.getByRole('button', { name: '保存', exact: true }).click()
    await page.getByRole('button', { name: 'empty-renamed 包含 0 张卡片', exact: true }).waitFor()
    await page.getByRole('button', { name: '删除标签：empty-renamed', exact: true }).click()
    await page.getByRole('dialog', { name: '删除标签', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click()
    await page.getByRole('button', { name: '重命名标签：old', exact: true }).click()
    let dialog = page.getByRole('dialog', { name: '重命名标签', exact: true })
    await dialog.getByRole('textbox', { name: '标签名称', exact: true }).fill('renamed')
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await page.getByRole('button', { name: '重命名标签：renamed', exact: true }).waitFor()
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('vibe-word:settings:v1')).studyScope), { version: 2, mode: 'custom', rules: [{ deckIds: null, tags: ['renamed'] }] })
    await page.getByRole('button', { name: '重命名标签：renamed', exact: true }).click()
    await dialog.getByRole('textbox').fill('shared')
    await dialog.getByText('该标签已存在，保存后将合并标签。').waitFor()
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await page.getByRole('button', { name: '重命名标签：renamed', exact: true }).waitFor({ state: 'detached' })
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('vibe-word:cards:v1')).map(c => c.tags)), [['shared'], ['shared'], []])
    await page.getByRole('searchbox', { name: '搜索标签' }).fill('missing')
    await page.getByText('没有匹配的标签', { exact: true }).waitFor()
    await page.getByRole('searchbox', { name: '搜索标签' }).fill('')
    for (const width of [1280, 390, 320]) {
      await page.setViewportSize({ width, height: 900 })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow at ${width}`)
      await page.screenshot({ path: `/tmp/vibe-tag-manager-${width}.png`, fullPage: true })
    }
    await page.getByRole('button', { name: 'shared 包含 2 张卡片', exact: true }).click()
    assert.match(await page.getByRole('combobox', { name: '按标签筛选' }).innerText(), /shared/)
    await page.getByRole('button', { name: '管理标签', exact: true }).click()
    await page.getByRole('button', { name: '删除标签：shared', exact: true }).click()
    dialog = page.getByRole('dialog', { name: '删除标签', exact: true })
    await dialog.getByRole('button', { name: '取消', exact: true }).click()
    assert.equal(await page.locator('.tag-manager-row').count(), 1)
    await page.getByRole('button', { name: '删除标签：shared', exact: true }).click()
    await dialog.getByRole('button', { name: '确认删除', exact: true }).click()
    await page.getByText('暂无标签，创建一个标签开始整理。', { exact: true }).waitFor()
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('vibe-word:cards:v1')).map(c => [c.front, c.tags])), [['Alpha', []], ['Beta', []], ['Gamma', []]])
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('vibe-word:settings:v1')).studyScope), { version: 2, mode: 'custom', rules: [{ deckIds: null, tags: ['shared'] }] })
    assert.equal(await page.evaluate(() => localStorage.getItem('vibe-word:study:v2')), before)
    await page.reload()
    await page.getByRole('button', { name: '卡片库', exact: true }).click()
    await page.getByRole('button', { name: '管理标签', exact: true }).click()
    await page.getByText('暂无标签，创建一个标签开始整理。', { exact: true }).waitFor()
    assert.deepEqual(errors, [])
    console.log('PASS: tag rename, merge, browse, search, delete, persistence, scope, progress, and responsive layout')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
