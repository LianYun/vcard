const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({headless: true, executablePath: process.env.CHROME_EXECUTABLE})
  const page = await browser.newPage({viewport: {width: 1280, height: 900}})
  const errors = []; page.on('pageerror', e => errors.push(String(e)))
  await page.goto(process.env.STUDY_TEST_URL || 'http://127.0.0.1:5189')
  await page.evaluate(() => {
    localStorage.clear()
    localStorage.setItem('vibe-word:language:v1', 'zh-Hans')
    localStorage.setItem('vibe-word:cards:v1', JSON.stringify([{id:'one', front:'serendipity', back:'Original answer', example:'Original example', tags:['travel'], noteId:'pair', createdAt:Math.floor(Date.now()/1000)}, {id:'two',front:'other',back:'Sibling',noteId:'pair',createdAt:Math.floor(Date.now()/1000)}]))
    localStorage.setItem('vibe-word:progress:v1', JSON.stringify({one:{cardId:'one',due:'2020-01-01',ease:2.5,interval:6,repetitions:2,lastReviewedAt:1,phase:'review'}}))
    localStorage.setItem('vibe-word:decks:v1',JSON.stringify([{id:'default',name:'默认牌组'},{id:'target',name:'目标牌组'}]))
  })
  await page.reload()
  const before = await page.evaluate(() => localStorage.getItem('vibe-word:progress:v1'))
  await page.getByRole('button',{name:'卡片库',exact:true}).click()
  await page.getByRole('button',{name:'serendipity',exact:false}).first().click()
  await page.locator('.library-row').filter({hasText:'serendipity'}).getByRole('button',{name:'编辑',exact:true}).click()
  const editor = page.locator('.card-editor-page')
  await editor.getByRole('heading',{name:'编辑卡片',exact:true}).waitFor()
  async function source(side, text) {
    const section = editor.locator('.card-editor-fields section').filter({has:page.getByRole('heading',{name:side,exact:false})}).first()
    await section.getByRole('button',{name:'源码',exact:true}).click()
    await section.getByRole('textbox').fill(text)
  }
  await source('正面','serendipity updated')
  await source('背面','**Updated answer**')
  await editor.getByRole('combobox').selectOption('target')
  await editor.getByRole('textbox',{name:'标签（用逗号分隔，清空可移除）'}).fill('travel, new')
  await editor.getByRole('textbox',{name:'例句 1',exact:true}).fill('Updated example')
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'继续编辑',exact:true}).click()
  assert.equal(await editor.getByRole('textbox',{name:'正面 源码'}).inputValue(),'serendipity updated')
  await page.screenshot({path:'design/card-editor-desktop.png'})
  await editor.getByRole('button',{name:'保存修改',exact:true}).click()
  await editor.waitFor({state:'detached'})
  const edited = await page.evaluate(() => JSON.parse(localStorage.getItem('vibe-word:cards:v1')))
  assert.equal(edited[0].back,'**Updated answer**');assert.equal(edited[0].deckId,'target');assert.deepEqual([...edited[0].tags].sort(),['new','travel']);assert.equal(edited[0].noteId,'pair');assert.equal(edited[1].back,'Sibling')
  assert.equal(await page.evaluate(()=>localStorage.getItem('vibe-word:progress:v1')), before)
  // A stale or deleted card never overwrites newer content or recreates a card.
  await page.locator('.library-row').filter({hasText:'serendipity'}).getByRole('button',{name:'编辑',exact:true}).click()
  await source('背面','Stale draft')
  await page.evaluate(()=>{const cs=JSON.parse(localStorage.getItem('vibe-word:cards:v1'));cs[0].back='External edit';localStorage.setItem('vibe-word:cards:v1',JSON.stringify(cs))})
  await editor.getByRole('button',{name:'保存修改',exact:true}).click()
  await editor.getByRole('alert').filter({hasText:'卡片内容已更新'}).waitFor()
  assert.equal(await editor.getByRole('textbox',{name:'背面 源码'}).inputValue(),'Stale draft')
  await page.evaluate(()=>{const cs=JSON.parse(localStorage.getItem('vibe-word:cards:v1'));localStorage.setItem('vibe-word:cards:v1',JSON.stringify(cs.filter(c=>c.id!=='one')))})
  await editor.getByRole('button',{name:'保存修改',exact:true}).click()
  await editor.getByRole('alert').filter({hasText:'卡片已删除'}).waitFor()
  await page.keyboard.press('Escape');await page.getByRole('button',{name:'放弃修改',exact:true}).click()
  // Creation shares the same page, seeds progress, and retains selected metadata.
  await page.getByRole('button',{name:'添加',exact:true}).click()
  await page.getByRole('button',{name:'创建卡片',exact:true}).last().click()
  await source('正面','Created question')
  await source('背面','Created answer')
  await page.setViewportSize({width:390,height:844})
  assert(await editor.evaluate(el=>el.scrollWidth<=el.clientWidth))
  await editor.locator('.card-editor-front .card-editor-preview').getByText('Created question',{exact:true}).waitFor()
  await page.screenshot({path:'design/card-editor-mobile.png'})
  await editor.getByRole('button',{name:'创建卡片',exact:true}).click()
  await editor.getByRole('status').filter({hasText:'卡片已创建'}).waitFor()
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('vibe-word:cards:v1')).filter(c=>c.front==='Created question').length),1)
  await editor.getByRole('button',{name:'‹ 返回',exact:true}).click()
  // Learning restores the current card and flipped side without grading it.
  await page.setViewportSize({width:1280,height:900})
  await page.getByRole('button',{name:'今日练习',exact:true}).click()
  await page.getByRole('button',{name:'开始学习',exact:true}).first().click()
  await page.locator('.study-card').waitFor()
  await page.locator('.study-card').click()
  const studyBefore=await page.evaluate(()=>({progress:localStorage.getItem('vibe-word:progress:v1'),session:localStorage.getItem('vibe-word:study:v2')}))
  await page.getByRole('button',{name:'更多操作',exact:true}).click()
  await page.getByRole('button',{name:'编辑内容',exact:true}).click()
  await source('背面','Edited while studying')
  await editor.getByRole('button',{name:'保存修改',exact:true}).focus()
  await page.keyboard.press('d')
  assert.equal(await page.evaluate(()=>localStorage.getItem('vibe-word:progress:v1')),studyBefore.progress)
  await editor.getByRole('button',{name:'保存修改',exact:true}).click();await editor.waitFor({state:'detached'})
  await page.locator('.study-card.is-back').getByText('Edited while studying',{exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>localStorage.getItem('vibe-word:progress:v1')),studyBefore.progress)
  assert.equal(await page.evaluate(()=>localStorage.getItem('vibe-word:study:v2')),studyBefore.session)
  await page.locator('.study-header').getByRole('button',{name:'‹ 返回',exact:true}).click()
  await page.getByRole('button',{name:'快速学习',exact:true}).click()
  await page.getByRole('button',{name:'开始快速学习',exact:false}).click()
  await page.locator('.browse-page .study-card').click()
  await page.getByRole('button',{name:'编辑内容',exact:true}).click()
  await source('背面','Edited in quick study')
  await page.setViewportSize({width:320,height:800})
  assert(await editor.evaluate(el=>el.scrollWidth<=el.clientWidth))
  await page.evaluate(()=>document.documentElement.dataset.theme='dark')
  assert.equal(await editor.evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(32, 32, 34)')
  await page.screenshot({path:'design/card-editor-mobile-dark.png'})
  await editor.getByRole('button',{name:'保存修改',exact:true}).click();await editor.waitFor({state:'detached'})
  await page.locator('.browse-page .study-card.is-back').getByText('Edited in quick study',{exact:true}).waitFor()
  assert.equal(await page.evaluate(()=>localStorage.getItem('vibe-word:progress:v1')),studyBefore.progress)
  assert.deepEqual(errors,[])
  await browser.close()
  console.log('PASS editor: metadata, progress, unsaved guard, conflict/deletion, creation, 390px/320px preview, dark theme, study/quick-study restoration, shortcut isolation')
})().catch(e=>{console.error(e);process.exit(1)})
