const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE })
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(String(error)))
    await page.route('https://ai.fixture/**', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ choices: [{ message: { content: JSON.stringify({ word: 'queueword', phonetic: '/test/', definition: '测试含义', example: 'Test example.', exampleTranslation: '测试例句', etymology: 'origin', roots: 'root', similar: 'similar', chineseHint: '反向提示' }) } }] }) }))
    await page.addInitScript(() => {
      localStorage.setItem('vibe-word:language:v1', '"zh-Hans"')
      localStorage.setItem('vibe-word:llm:v1', JSON.stringify({ baseURL: 'https://ai.fixture/v1', apiKey: 'fixture-only', model: 'test' }))
    })
    await page.goto(process.env.STUDY_TEST_URL || 'http://127.0.0.1:5193')
    const nav = name => page.getByRole('navigation').getByRole('button', { name })
    await nav('添加').click()
    await page.getByRole('tab', { name: 'AI 生成', exact: true }).click()
    await page.getByRole('textbox', { name: '学习内容', exact: true }).fill('queueword')
    await page.getByRole('button', { name: '生成卡片', exact: true }).click()
    await nav(/^任务队列/).click()
    const detail = page.locator('.task-detail')
    const confirm = () => detail.getByRole('button', { name: '入库当前卡', exact: true })
    await confirm().waitFor()
    assert.equal(await detail.getByRole('tab').count(), 2)
    await detail.getByRole('tab', { name: '中 → 英 待审核' }).click()
    assert.equal(await detail.getByRole('tab', { name: '中 → 英 待审核' }).getAttribute('aria-selected'), 'true')
    await detail.getByRole('tab', { name: '中 → 英 待审核' }).press('ArrowLeft')
    assert.equal(await detail.getByRole('tab', { name: '英 → 中 待审核' }).getAttribute('aria-selected'), 'true')
    // Hold a confirmation briefly to exercise visible feedback and click gating.
    await page.evaluate(async () => {
      const { generationQueue } = await import('/src/lib/generationQueue.ts')
      const original = generationQueue.confirm
      generationQueue.confirm = async (...args) => { await new Promise(resolve => setTimeout(resolve, 250)); return original(...args) }
    })
    await confirm().click()
    await detail.getByRole('button', { name: '正在保存…', exact: true }).waitFor()
    assert.equal(await detail.getByRole('button', { name: '正在保存…', exact: true }).isDisabled(), true)
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('vibe-word:cards:v1') || '[]').length === 1)
    await confirm().waitFor()
    assert.equal(await detail.getByRole('tab', { name: '中 → 英 待审核' }).getAttribute('aria-selected'), 'true')
    await detail.getByRole('tab', { name: '英 → 中 已入库' }).click()
    assert.equal(await confirm().count(), 0)
    await detail.getByRole('tab', { name: '中 → 英 待审核' }).click()
    await confirm().click()
    await page.waitForFunction(() => JSON.parse(localStorage.getItem('vibe-word:cards:v1') || '[]').length === 2)
    await confirm().waitFor({ state: 'detached' })
    await detail.getByRole('status').getByText('审核完成', { exact: true }).waitFor()
    assert.equal(await detail.getByRole('tab').count(), 2)
    await nav('卡片库').click()
    await page.waitForFunction(() => document.querySelector('.mac-main')?.textContent.includes('queueword'))
    await page.reload()
    await nav(/^任务队列/).click()
    await page.getByRole('button', { name: '已结束', exact: true }).click()
    await detail.getByRole('heading', { name: 'queueword', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('vibe-word:cards:v1')).length), 2)
    assert.deepEqual(errors, [])
    console.log('PASS confirmation feedback, disabled button, next draft, library refresh on return and persisted completion')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
