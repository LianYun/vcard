const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
;(async () => {
 const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_EXECUTABLE})
 try {
 const page = await browser.newPage({viewport:{width:1280,height:900}})
 const errors=[];page.on('pageerror', e=>errors.push(String(e)))
 await page.goto(process.env.STUDY_TEST_URL || 'http://127.0.0.1:5189')
 await page.evaluate(()=>{localStorage.clear();localStorage.setItem('vibe-word:language:v1','zh-Hans');localStorage.setItem('vibe-word:cards:v1',JSON.stringify([{id:'existing',front:'Existing card',back:'Answer',tags:['tag']}]))})
 await page.reload()
 await page.getByRole('button',{name:'卡片库',exact:true}).click()
 await page.getByRole('button',{name:'管理牌组',exact:true}).click()
 await page.getByRole('button',{name:'＋ 新建牌组',exact:true}).click()
 let dialog=page.locator('dialog[open]').last()
 await dialog.getByRole('textbox',{name:'名称',exact:true}).fill('Topic')
 await dialog.getByRole('button',{name:'保存',exact:true}).click()
 await page.getByRole('heading',{name:'Topic',exact:true}).waitFor()
 await page.getByRole('button',{name:'从现有卡片移入',exact:true}).click()
 dialog=page.locator('dialog[open]').last()
 await dialog.getByRole('checkbox',{name:'Existing card'}).check()
 await dialog.getByRole('button',{name:'确认移动'}).click()
 await page.getByRole('button',{name:'开始学习',exact:true}).click()
 await page.locator('.deck-study-label').filter({hasText:'Topic'}).waitFor()
 await page.locator('.study-header').getByRole('button',{name:'‹ 返回',exact:true}).click()
 await page.getByRole('heading',{name:'Topic',exact:true}).waitFor()
 await page.getByRole('button',{name:'今日练习',exact:true}).click()
 await page.getByRole('button',{name:'卡片库',exact:true}).click()
 await page.getByRole('heading',{name:'Topic',exact:true}).waitFor()
 const before = await page.evaluate(()=>localStorage.getItem('vibe-word:study:v2'))
 await page.getByRole('button',{name:'添加卡片',exact:true}).click()
 assert.match(await page.getByRole('combobox',{name:'牌组',exact:true}).inputValue(),/.+/)
 await page.getByRole('button',{name:'创建卡片',exact:true}).last().click()
 const editor=page.locator('.card-editor-page')
 await editor.waitFor()
 const topicId=await editor.getByRole('combobox',{name:'牌组',exact:true}).inputValue()
 await editor.getByRole('button',{name:'＋ 新建牌组',exact:true}).click()
 dialog=page.locator('.deck-dialog[open]').last()
 await dialog.getByRole('textbox',{name:'名称',exact:true}).fill('Inline')
 await dialog.getByRole('button',{name:'保存',exact:true}).click()
 assert.notEqual(await editor.getByRole('combobox',{name:'牌组',exact:true}).inputValue(),topicId)
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('vibe-word:cards:v1')).length),1,'creating a deck must not submit parent card form')
 await editor.getByRole('button',{name:'‹ 返回',exact:true}).click()
 await page.getByRole('button',{name:'放弃修改',exact:true}).click()
 await page.getByRole('button',{name:'卡片库',exact:true}).click()
 await page.getByRole('heading',{name:'Topic',exact:true}).waitFor()
 for(const width of [390,320]) {
  await page.setViewportSize({width,height:850})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`overflow ${width}`)
  await page.screenshot({path:`/tmp/vibe-decks-${width}.png`,fullPage:true})
 }
 await page.setViewportSize({width:1280,height:900})
 await page.getByText('管理牌组',{exact:true}).click()
 await page.getByRole('button',{name:'新建子牌组'}).click()
 dialog=page.locator('.deck-dialog[open]').last()
 await dialog.getByRole('textbox',{name:'名称',exact:true}).fill('Child')
 assert.equal(await dialog.getByRole('combobox',{name:'父牌组'}).inputValue(),topicId)
 await dialog.getByRole('button',{name:'保存',exact:true}).click()
 await page.getByRole('heading',{name:'Topic::Child',exact:true}).waitFor()
 await page.getByRole('button',{name:'‹ 返回牌组'}).click()
 await page.getByRole('button',{name:/^Topic /}).click()
 await page.getByText('管理牌组',{exact:true}).click()
 await page.getByRole('button',{name:'删除牌组（保留卡片）'}).click()
 await page.locator('dialog[open]').getByRole('button',{name:'确认删除'}).click()
 await page.getByRole('button',{name:/^Child /}).waitFor()
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('vibe-word:cards:v1'))[0].deckId),'default')
 assert.equal(await page.evaluate(()=>localStorage.getItem('vibe-word:study:v2')),before,'move/delete keeps scheduling')
 await page.getByRole('button',{name:'全部卡片',exact:true}).click()
 await page.getByRole('button',{name:'批量选择',exact:true}).click()
 await page.getByRole('button',{name:'全选',exact:true}).click()
 await page.getByRole('button',{name:'移动到…',exact:true}).click()
 dialog=page.locator('.deck-dialog[open]').last()
 await dialog.getByRole('button',{name:'＋ 新建牌组',exact:true}).click()
 let nested=page.locator('.deck-dialog[open]').last()
 await nested.getByRole('textbox',{name:'名称',exact:true}).fill('Moved')
 await nested.getByRole('button',{name:'保存',exact:true}).click()
 dialog=page.locator('.deck-dialog[open]').last()
 assert.equal(await dialog.getByRole('combobox',{name:'牌组',exact:true}).locator('option:checked').textContent(),'Moved')
 await dialog.getByRole('button',{name:'确认移动',exact:true}).click()
 const moved = await page.evaluate(()=>JSON.parse(localStorage.getItem('vibe-word:decks:v1')).find(d=>d.name==='Moved').id)
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('vibe-word:cards:v1'))[0].deckId),moved)
 assert.equal(await page.evaluate(()=>localStorage.getItem('vibe-word:study:v2')),before)
 assert.deepEqual(errors,[])
 console.log('PASS deck creation, collect, study/return, inline creation isolation, mobile layout, hierarchy and safe deletion')
 } finally { await browser.close() }
})().catch(e=>{console.error(e);process.exit(1)})
