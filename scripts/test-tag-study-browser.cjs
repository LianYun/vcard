// Run against Vite with an isolated Playwright browser context.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_EXECUTABLE });
  try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [];
    page.on('pageerror', e => errors.push(String(e)));
    await page.goto(process.env.STUDY_TEST_URL || 'http://127.0.0.1:5194');
    await page.evaluate(() => {
      localStorage.clear(); localStorage.setItem('vibe-word:language:v1', 'zh-Hans');
      const cards = [{ id: 'a', tags: ['work'] }, { id: 'b', tags: ['work', 'travel'] }, { id: 'c', tags: ['travel'] }, { id: 'd' }, { id: 'e', tags: ['work'] }, { id: 'f', tags: ['travel'] }].map(c => ({ ...c, front: c.id, back: `Meaning ${c.id}` }));
      localStorage.setItem('vibe-word:cards:v1', JSON.stringify(cards));
      localStorage.setItem('vibe-word:settings:v1', JSON.stringify({ newCardsPerDay: 1 }));
      localStorage.setItem('vibe-word:progress:v1', JSON.stringify(Object.fromEntries(['e', 'f'].map(id => [id, { cardId: id, ease: 2.5, interval: 6, repetitions: 2, due: '2020-01-01', lastReviewedAt: Date.now() - 86400000, phase: 'review' }]))));
    });
    await page.reload();
    const button = name => page.getByRole('button', { name, exact: true });
    await button('设置').click();
    await page.getByRole('radio', { name: '指定标签', exact: true }).check();
    await button('保存配置').click();
    await page.getByRole('alert').filter({ hasText: '请至少选择一个标签' }).waitFor();
    await page.getByRole('checkbox', { name: /work/ }).check();
    await button('保存配置').click();
    await page.getByText('已保存', { exact: true }).waitFor();
    await button('卡片').click();
    await page.getByLabel('按标签筛选').selectOption('tag:travel');
    await button('开始学习').click();
    await page.locator('.study-content .study-scope-label').filter({ hasText: 'work' }).waitFor();
    await page.locator('.study-card').waitFor();
    let data = await page.evaluate(() => JSON.parse(localStorage.getItem('vibe-word:study:v2')));
    assert.deepEqual(Object.values(data.issued).flat(), ['a']);
    await button('‹ 返回我的卡片').click();
    await button('设置').click();
    await page.getByRole('checkbox', { name: /work/ }).uncheck();
    await page.getByRole('checkbox', { name: /travel/ }).check();
    await button('保存配置').click();
    await page.getByText('已保存', { exact: true }).waitFor();
    await button('卡片').click();
    await button('继续上次学习 · work').click();
    await page.locator('.study-content .study-scope-label').filter({ hasText: 'work' }).waitFor();
    await button('‹ 返回我的卡片').click();
    await button('按标签学习').click();
    await page.getByRole('checkbox', { name: /travel/ }).waitFor();
    const before = await page.evaluate(() => localStorage.getItem('vibe-word:study:v2'));
    await page.getByText('本次可学：待复习 1 张 · 新卡 0 张', { exact: true }).waitFor();
    await page.getByRole('checkbox', { name: /work/ }).check();
    await page.getByText('本次可学：待复习 3 张 · 新卡 0 张', { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem('vibe-word:study:v2')), before);
    await page.getByRole('checkbox', { name: /work/ }).uncheck();
    await button('开始学习 · 1 张').click();
    await page.locator('.study-card').waitFor();
    assert.match(await page.locator('.study-card').innerText(), /f/);
    await button('‹ 返回标签筛选').click();
    assert.equal(await page.getByRole('checkbox', { name: /travel/ }).isChecked(), true);
    await button('清空').click();
    assert.equal(await button('开始学习 · 0 张').isDisabled(), true);
    await page.getByRole('checkbox', { name: /未打标签/ }).check();
    await page.getByText('今日新卡额度已用完', { exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: '/tmp/tag-study-mobile.png', fullPage: true });
    await button('‹ 返回我的卡片').click();
    await page.reload();
    await page.locator('.library-scope').filter({ hasText: 'travel' }).waitFor();
    assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('vibe-word:settings:v1')).studyScope), ['travel']);
    assert.deepEqual(errors, []);
    console.log('PASS settings validation/persistence, independent library filter, frozen resume scope, read-only union preview, shared budget, return selection and 390px layout');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
